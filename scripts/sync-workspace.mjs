import fs from "node:fs/promises";
import ts from "typescript";

// Existing Express ports are generated from these domain services. Never copy
// the Next proxy workspace-actions.ts or the backend-specific DB adapter.
const files = ["routing", "stock-ledger", "transfer-actions", "inventory-actions", "request-actions", "request-policy", "delivery-planning", "permissions", "forecast", "distribution-location", "parts-consumption-contract", "parts-consumption", "industrial-links"];
let outdated = false;
for (const file of files) {
  const source = await fs.readFile(`lib/${file}.ts`, "utf8");
  const result = "// Generated by scripts/sync-workspace.mjs from lib/" + file + ".ts.\n" + ts.transpileModule(source, {
    compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS, esModuleInterop: true },
    fileName: `${file}.ts`,
  }).outputText;
  const destination = `backend/src/workspace/${file}.js`;
  if (process.argv.includes("--check")) {
    if ((await fs.readFile(destination, "utf8")).replaceAll("\r\n", "\n") !== result.replaceAll("\r\n", "\n")) {
      console.error(`Domain service out of sync: ${file}`);
      outdated = true;
    }
  } else await fs.writeFile(destination, result);
}
if (outdated) process.exitCode = 1;
